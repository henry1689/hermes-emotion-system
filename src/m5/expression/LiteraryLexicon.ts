/**
 * 获取指定维度和强度的文学短语
 */
export function getPhrase(dim: string, intensity: number): string {
  const level = intensity > 0.6 ? 'high' : intensity > 0.3 ? 'mid' : 'low';
  const key = `${dim}_${level}`;
  const entry = LITERARY_LEXICON[key];
  if (!entry) return '';
  return entry.phrases[Math.floor(Math.random() * entry.phrases.length)];
}

/**
 * 获取多个短语组合（用于长回应）
 */
export function getPhrases(dim: string, intensity: number, count: number): string[] {
  const result: string[] = [];
  for (let i = 0; i < count; i++) {
    result.push(getPhrase(dim, intensity));
  }
  return result.filter(Boolean);
}
